namespace Coficab.TestDataSeeder;

/// <summary>
/// Stable markers so generated rows are identifiable and idempotent across runs.
/// </summary>
internal static class TestDataMarkers
{
    public const string Tag = "[TESTDATA]";
    public const string CreatedBy = "TESTDATA_SEED";
    public const string EmailDomain = "coficab.test";
    public const string OrgName = "[TESTDATA] Seed Organization";
    public const string DescriptionSuffix = " | Generated by Coficab.TestDataSeeder (idempotent).";

    public static string EmployeeEmail(int index1Based)
        => $"seed.employee{index1Based:00}@{EmailDomain}";

    public static bool IsEmployeeEmail(string? email)
        => !string.IsNullOrWhiteSpace(email)
           && email.EndsWith("@" + EmailDomain, StringComparison.OrdinalIgnoreCase)
           && email.StartsWith("seed.employee", StringComparison.OrdinalIgnoreCase);

    public static string ClaimTitle(int index1Based)
        => $"{Tag} Claim {index1Based:000}";

    public static string PlanTitle(int index1Based)
        => $"{Tag} Plan {index1Based:000}";

    public static string PlanActionTitle(int planIndex1Based, int actionOrder)
        => $"{Tag} Plan {planIndex1Based:000} / Action {actionOrder}";

    public static bool IsTestClaimTitle(string? title)
        => !string.IsNullOrWhiteSpace(title)
           && title.StartsWith($"{Tag} Claim ", StringComparison.Ordinal);

    public static bool IsTestPlanTitle(string? title)
        => !string.IsNullOrWhiteSpace(title)
           && title.StartsWith($"{Tag} Plan ", StringComparison.Ordinal)
           && !title.Contains(" / Action ", StringComparison.Ordinal);

    public static bool IsTestPlanActionTitle(string? title)
        => !string.IsNullOrWhiteSpace(title)
           && title.StartsWith($"{Tag} Plan ", StringComparison.Ordinal)
           && title.Contains(" / Action ", StringComparison.Ordinal);
}
